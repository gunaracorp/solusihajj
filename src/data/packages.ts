/** Helper itinerary umrah reguler (dipakai paket non-featured; featured ditulis manual) */
function regItinerary(days: number, city: string): ItineraryDay[] {
  const base: ItineraryDay[] = [
    { day: 1, title: "Keberangkatan dari " + city, desc: "Gladi bersih & briefing singkat di bandara. Penerbangan menuju Jeddah (transit sesuai jadwal maskapai). Tiba di King Abdulaziz International Airport, proses imigrasi, lalu bus menuju Makkah.", location: "JKT" },
    { day: 2, title: "Tiba di Tanah Suci — Makkah", desc: "Perjalanan darat ke Makkah dengan persinggahan miqat Qarnul Manazil (Sayl Al-Kabir) untuk niat ihram. Check-in hotel, istirahat memulihkan tenaga.", location: "MK" },
    { day: 3, title: "Umrah Pertama Bersama Mutawif", desc: "Ba'da Subuh menuju Masjidil Haram. Pendampingan lengkap tawaf, sa'i, dan tahallul oleh mutawif bersertifikat Manasik Kemenag.", location: "MK" },
  ];
  const makkahDays = Math.max(2, days - 6); // hari ibadah di Makkah (selain hari 1-3)
  const mid: ItineraryDay[] = [];
  const ziarahs = [
    "Ibadah mandiri di Masjidil Haram ba'da Subuh. Sore: ziarah internal Makkah — Jabal Rahmah, Masjid Aisyah (miqat), pabrik kain kiswah.",
    "Kajian ba'da Subuh bersama ustadz pendamping. Waktu ibadah mandiri; siang istirahat, malam ziarah Mina, Arafah, dan Muzdalifah.",
    "Ibadah mandiri dan kebebasan beribadah sesuai ritme pribadi. Opsional: tawaf sunnah & shalat di Hijr Ismail (hati-hati keramaian).",
  ];
  for (let i = 0; i < makkahDays; i++) {
    const z = ziarahs[i % ziarahs.length];
    mid.push({
      day: 4 + i,
      title: i === 0 ? "Ibadah Mandiri & Ziarah Makkah" : "Hari Ibadah di Makkah",
      desc: z,
      location: "MK",
    });
  }
  const tail: ItineraryDay[] = [
    { day: 4 + makkahDays, title: "Menuju Madinah", desc: "Check-out, perjalanan Makkah–Madinah (~4,5 jam). Tiba, check-in hotel dekat Masjid Nabawi, istirahat.", location: "MD" },
    { day: 5 + makkahDays, title: "Ziarah Masjid Nabawi & Raudhah", desc: "Shalat di Masjid Nabawi, kunjungan Raudhah sesuai jadwal kuota aplikasi Nusuk, makam Rasulullah ﷺ, dan Baab as-Salam.", location: "MD" },
    { day: 6 + makkahDays, title: "Ziarah Sekitar Madinah", desc: "Masjid Quba (niat umrah sunnah di Masjid Quba), Masjid Qiblatain, Jabal Uhud, kurma pasar taiyiba. Malam: ibadah mandiri.", location: "MD" },
    { day: days, title: "Pulang ke Indonesia", desc: "Check-out, transfer ke Bandara Prince Mohammad bin Abdulaziz Madinah. Penerbangan menuju Indonesia, tiba keesokan harinya (bagi grup malam).", location: "JKT" },
  ];
  return [...base, ...mid, ...tail].slice(0, days).map((d, i) => ({ ...d, day: i + 1 }));
}

/** Helper tanggal keberangkatan */
function dates(list: Array<[string, string, number, number, number]>): PackageDate[] {
  // [departISO, returnISO, quota, remaining, priceDelta]
  const rooms: PackageDate["roomType"][] = ["quad", "quad", "triple"];
  return list.map(([depart, returnDate, quota, remaining, priceDelta], i) => ({
    id: depart,
    depart,
    returnDate,
    quota,
    remaining,
    roomType: rooms[i % rooms.length],
    priceDelta,
  }));
}

