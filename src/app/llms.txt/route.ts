/**
 * /llms.txt — manifest machine-discovery untuk LLM, asisten AI & agent crawler.
 * Konvensi llms.txt (llmstxt.org): H1 judul proyek + blockquote ringkasan +
 * section H2 berisi tautan Markdown dengan deskripsi satu baris.
 * SolusiHajj v2.1.0 — Prioritas 5 (machine-discovery layer).
 * Seluruh URL absolut dari SITE (@/lib/og) — tidak ada hardcode domain.
 */
import { SITE } from "@/lib/og";
import { RELEASE_LABEL } from "@/lib/version";
import { packageList } from "@/data/packages";
import { articleList } from "@/data/articles";

/** Format rupiah ringkas ("Rp 28.500.000") — lokal, tanpa dependensi UI. */
function rupiah(n: number): string {
  return `Rp ${n.toLocaleString("id-ID")}`;
}

/** Baris tautan Markdown konvensi llms.txt. */
function mdLink(path: string, title: string, desc: string): string {
  return `- [${title}](${SITE}${path}): ${desc}`;
}

export function GET(): Response {
  // 5 paket rating tertinggi dari 27 (representatif, bukan daftar lengkap).
  const topPackages = [...packageList].sort((a, b) => b.rating - a.rating).slice(0, 5);
  // 8 artikel representatif dari 112 (seed edukasi + mesin konten E-E-A-T).
  const topArticles = articleList.slice(0, 8);

  const body = `# SolusiHajj

> Marketplace haji & umrah terpercaya di Asia — 3.966 organisasi terdata (PPIU, PIHK, UTO, USP, BPW), 27 paket umrah, 210 layanan, escrow syariah 40/40/20, review hanya dari jamaah nyata. Situs resmi: solusihajj.web.id. Pure marketplace: penyelenggara yang menjual, SolusiHajj yang memverifikasi.

Release: ${RELEASE_LABEL}

## Halaman Utama
- [SolusiHajj — Amanah Anda, Aman](${SITE}/): portal utama marketplace umrah & haji — paket terverifikasi, direktori 3.966 organisasi, escrow syariah, dan NurMatch AI.

## Paket Umrah
- [Katalog Paket Umrah](${SITE}/paket): 27 paket terverifikasi 5 lapis dengan harga transparan, jarak hotel ke Haram, dan review Saksi Jamaah.
${topPackages
  .map((p) =>
    mdLink(
      `/paket/${p.slug}`,
      p.title,
      `Umrah ${p.durationDays} hari dari ${p.departCity} · mulai ${rupiah(p.basePrice)} · rating ${p.rating.toFixed(1)}/5 (${p.reviewCount} review).`
    )
  )
  .join("\n")}

## Direktori Nasional
- [Direktori Nasional Penyelenggara](${SITE}/direktori): 3.966 profil organisasi (PPIU, PIHK, UTO, USP, BPW) dengan nomor izin, status, dan sumber data resmi Kemenag/Kemenhaj.
- [Katalog Faset](${SITE}/katalog): telusuri seluruh organisasi berdasarkan tipe, provinsi, dan status verifikasi.
- [Katalog PPIU](${SITE}/katalog/ppiu): faset khusus penyelenggara perjalanan ibadah umrah berizin Kemenag.
- [Katalog PIHK](${SITE}/katalog/pihk): faset khusus penyelenggara haji khusus (PIHK) terdata nasional.

## Layanan & Matrix SEO
- [Direktori Layanan](${SITE}/layanan): 210 layanan × 45 kota keberangkatan = 9.450 halaman kombinasi layanan-kota dengan lead capture terverifikasi.

## Artikel & Panduan
- [Artikel & Panduan](${SITE}/artikel): 112 artikel E-E-A-T (panduan, biaya, manasik, visa, hotel) dengan author dan tanggal review.
${topArticles
  .map((a) => mdLink(`/artikel/${a.slug}`, a.title, `${a.excerpt.slice(0, 120).trim()}…`))
  .join("\n")}

## Glosarium
- [Glosarium Haji & Umrah](${SITE}/glosarium): kamus istilah ibadah A–Z dengan arti, tulisan Arab, dan penjelasan lengkap untuk jamaah.

## Alat Publik
- [Perbandingan Paket](${SITE}/bandingkan): bandingkan paket umrah berdampingan — harga, hotel, durasi, maskapai, dan rating jamaah.

## English
- [Home (EN)](${SITE}/en): English entry point of the SolusiHajj umrah & haji marketplace.
- [Services (EN)](${SITE}/en/services): verified service directory in English.
- [Packages (EN)](${SITE}/en/packages): umrah package catalog in English.
- [Directory (EN)](${SITE}/en/directory): national organizer directory in English.

## Data & Machine Endpoints
- [Sitemap XML](${SITE}/sitemap.xml): indeks URL lengkap untuk crawler (± 13.984 URL).
- [RSS Feed](${SITE}/feed.xml): kanal RSS 2.0 kanonik — 50 artikel terbaru.
- [Version API](${SITE}/api/version): JSON identitas rilis (versi, codename, tanggal build).
- [Health API](${SITE}/api/health): probe kesehatan layanan.
- [Stats API](${SITE}/api/stats): JSON agregat statistik platform.
- [Companies API](${SITE}/api/r2/companies): JSON API direktori nasional 3.966 organisasi.

## Legal
- [Kebijakan Privasi](${SITE}/kebijakan-privasi): kebijakan pengumpulan & perlindungan data jamaah.
- [Syarat & Ketentuan](${SITE}/syarat-ketentuan): ketentuan penggunaan platform SolusiHajj.
- [FAQ](${SITE}/faq): pertanyaan yang sering diajukan jamaah.

Last updated: 2026-10-22 (Asia/Jakarta) · Generated by SolusiHajj Release System
`;

  return new Response(body, {
    status: 200,
    headers: {
      "Content-Type": "text/plain; charset=utf-8",
      "Cache-Control": "public, max-age=3600",
    },
  });
}
